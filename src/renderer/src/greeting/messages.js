const KEY = 'ct-greeting-queue'

function shuffled(n, avoidFirst) {
  const a = Array.from({ length: n }, (_, i) => i)
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[a[i], a[j]] = [a[j], a[i]]
  }
  // Never show the same line twice in a row across a reshuffle
  if (a.length > 1 && a[0] === avoidFirst) [a[0], a[1]] = [a[1], a[0]]
  return a
}

export function nextMessage() {
  let state = null
  try { state = JSON.parse(localStorage.getItem(KEY) || 'null') } catch (_) {}
  if (!state || !Array.isArray(state.queue) || state.size !== MESSAGES.length) {
    state = { size: MESSAGES.length, queue: shuffled(MESSAGES.length), last: null }
  }
  if (!state.queue.length) state.queue = shuffled(MESSAGES.length, state.last)
  const index = state.queue.shift()
  state.last = index
  try { localStorage.setItem(KEY, JSON.stringify(state)) } catch (_) {}
  return MESSAGES[index] ?? MESSAGES[0]
}

export function greetingFor(date = new Date()) {
  const h = date.getHours()
  if (h >= 5 && h < 12) return { text: 'Good morning', period: 'morning' }
  if (h >= 12 && h < 18) return { text: 'Good afternoon', period: 'afternoon' }
  return { text: 'Good evening', period: 'evening' }
}
